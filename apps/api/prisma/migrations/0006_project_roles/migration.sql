CREATE TABLE role_definitions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  permissions TEXT[] NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT role_definitions_key_check CHECK (key ~ '^[a-z][a-z0-9]*(-[a-z0-9]+)*$' AND key NOT IN ('admin', 'developer', 'tester', 'viewer'))
);
CREATE UNIQUE INDEX role_definitions_name_lower_key ON role_definitions (lower(name));
ALTER TABLE project_members ADD COLUMN role_id BIGINT;
ALTER TABLE project_members ADD CONSTRAINT project_members_role_id_fkey FOREIGN KEY (role_id) REFERENCES role_definitions(id) ON DELETE RESTRICT ON UPDATE CASCADE;
CREATE INDEX project_members_role_id_idx ON project_members(role_id);

