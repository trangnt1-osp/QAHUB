import { expect, test, type Locator } from '@playwright/test';
import { login } from './helpers';

test.use({ actionTimeout: 15_000 });

test('one project structure connects Epic, Module, Function, work items, periods and test cases across screens', async ({ page }) => {
  test.setTimeout(120_000);
  await login(page, 'admin@local.test', 'Admin@12345');
  const session = await (await page.request.post('/api/v1/auth/login', { data: { email: 'admin@local.test', password: 'Admin@12345' } })).json();
  const headers = { Authorization: `Bearer ${session.accessToken}` };
  const templates = await (await page.request.get('/api/v1/workflow-templates', { headers })).json();
  expect((await page.request.post('/api/v1/projects', { headers, data: { key: 'STRUI', name: 'Structure UI', workflowTemplateId: templates.find((row: { name: string }) => row.name === 'Tối giản').id } })).ok()).toBeTruthy();
  const metadata = async () => (await page.request.get('/api/v1/projects/STRUI/structure/options', { headers })).json();
  const choose = async (select: Locator, name: string) => {
    await expect(select).toBeEnabled();
    await select.press('ArrowDown');
    await page.locator('.ant-select-dropdown:visible').getByText(name, { exact: true }).click();
    const modalHeader = page.locator('.ant-modal-header:visible').last();
    if (await modalHeader.count()) await modalHeader.click();
    else await select.press('Escape');
  };
  const save = async (dialog: Locator) => {
    await dialog.getByRole('button', { name: /Lưu$/ }).click();
    await expect(dialog).toHaveCount(0);
  };
  await page.goto('/projects/STRUI/structure');
  await expect(page.getByRole('tab', { name: /Epic \/ Module/ })).toBeVisible();
  await expect(page.getByRole('columnheader', { name: 'Item key', exact: true })).toHaveCount(0);
  await page.getByRole('tab', { name: 'Module', exact: true }).click();
  await page.getByRole('button', { name: /Thêm Module/ }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Mã', { exact: true }).fill('MOD-UI');
  await dialog.getByLabel('Tên', { exact: true }).fill('Users');
  await save(dialog);
  await page.getByRole('tab', { name: 'Function', exact: true }).click();
  await page.getByRole('button', { name: /Thêm Function/ }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Mã', { exact: true }).fill('FN-UI');
  await dialog.getByLabel('Tên', { exact: true }).fill('Find users');
  await choose(dialog.getByLabel('Module', { exact: true }), 'MOD-UI · Users');
  await save(dialog);
  await page.getByRole('tab', { name: 'Epic', exact: true }).click();
  await page.getByRole('button', { name: /Thêm Epic/ }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Mã', { exact: true }).fill('EPIC-UI');
  await dialog.getByLabel('Tên', { exact: true }).fill('Shared Epic');
  await choose(dialog.getByLabel('Modules', { exact: true }), 'MOD-UI · Users');
  await save(dialog);
  const initial = await metadata();
  const epic = initial.epics.find((row: { code: string }) => row.code === 'EPIC-UI');
  const fn = initial.functions.find((row: { code: string }) => row.code === 'FN-UI');
  const module = initial.modules.find((row: { code: string }) => row.code === 'MOD-UI');
  expect(fn.moduleId).toBe(module.id);
  expect(epic.requirementId).toBeTruthy();
  const epicIssue = await (await page.request.get(`/api/v1/issues/${epic.key}`, { headers })).json();
  expect(epicIssue.moduleIds).toEqual([module.id]);
  const tcResponse = await page.request.post('/api/v1/projects/STRUI/test-cases', { headers, data: { functionId: fn.id, title: 'Find a known user', status: 'passed' } });
  expect(tcResponse.ok()).toBeTruthy();
  const tc = await tcResponse.json();

  await page.getByRole('banner').getByRole('button', { name: /Tạo/ }).click();
  dialog = page.getByRole('dialog', { name: 'Tạo item', exact: true });
  await choose(dialog.getByLabel('Dự án', { exact: true }), 'STRUI — Structure UI');
  await dialog.getByLabel('Tiêu đề', { exact: true }).fill('Linked UI task');
  await choose(dialog.getByRole('combobox', { name: 'Epic của item', exact: true }), 'EPIC-UI · Shared Epic');
  await choose(dialog.getByRole('combobox', { name: 'Function của item', exact: true }), 'FN-UI · Find users');
  const created = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().endsWith('/projects/STRUI/issues'));
  await dialog.getByRole('button', { name: 'Tạo', exact: true }).click();
  const task = await (await created).json();
  await expect(page).toHaveURL(new RegExp(`/browse/${task.key}$`));
  const getTask = async () => (await page.request.get(`/api/v1/issues/${task.key}`, { headers })).json();
  expect(await getTask()).toMatchObject({ parent: { id: epic.id }, functionIds: [fn.id], moduleIds: [module.id], explicitModuleIds: [] });
  const sprint = await (await page.request.post('/api/v1/projects/STRUI/sprints', { headers, data: { name: 'Sprint UI' } })).json();
  const current = await getTask();
  expect((await page.request.patch(`/api/v1/issues/${task.key}`, { headers, data: { version: current.version, sprintId: sprint.id } })).ok()).toBeTruthy();
  expect((await page.request.post('/api/v1/projects/STRUI/issues', { headers, data: { type: 'task', title: 'Unrelated UI task' } })).ok()).toBeTruthy();
  await page.goto(`/projects/STRUI/backlog?epicId=${epic.id}&moduleId=${module.id}&functionId=${fn.id}&sprintId=${sprint.id}`);
  await expect(page.getByTestId('backlog-scroll')).toContainText('Linked UI task');
  await expect(page.getByTestId('backlog-scroll')).not.toContainText('Unrelated UI task');
  await expect(page.getByRole('combobox', { name: 'Lọc Epic', exact: true }).locator('xpath=ancestor::div[contains(@class,"ant-select")][1]')).toContainText('EPIC-UI');
  await page.goto(`/projects/STRUI/test-cases?epicId=${epic.requirementId}`);
  await expect(page.getByTestId('checklist-summary')).toContainText('Total: 1');
  await expect(page.getByText(tc.code, { exact: true })).toBeVisible();
  await page.goto(`/projects/STRUI/test-cases?moduleId=${module.id}`);
  await expect(page.getByText('Module / Function', { exact: true })).toBeVisible();
  await expect(page.getByTestId('checklist-summary')).toContainText('Total: 1');

  // Rename an Epic without making work-derived Function scope permanent.
  await page.goto('/projects/STRUI/structure');
  await page.getByRole('tab', { name: 'Epic', exact: true }).click();
  const epicRow = page.getByRole('row').filter({ has: page.getByRole('cell', { name: 'EPIC-UI', exact: true }) });
  await epicRow.getByRole('button', { name: 'Sửa Epic', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Tên', { exact: true }).fill('Shared Epic renamed');
  await save(dialog);
  expect((await metadata()).epics.find((row: { code: string }) => row.code === 'EPIC-UI').explicitFunctionIds).toEqual([]);
  await page.goto(`/browse/${task.key}`);
  await expect(page.getByText(`${epic.key} Shared Epic renamed`, { exact: true })).toBeVisible();
  const fnSelect = page.locator('.ant-select').filter({ has: page.getByRole('combobox', { name: 'Function của item', exact: true }) });
  await fnSelect.locator('.ant-select-selection-item-remove').click();
  await expect.poll(async () => (await getTask()).functionIds).toEqual([]);
  expect((await getTask()).moduleIds).toEqual([]);
  await page.goto(`/projects/STRUI/test-cases?epicId=${epic.requirementId}`);
  await expect(page.getByTestId('checklist-summary')).toContainText('Total: 0');

  // Quick-create from Test cases uses the same canonical Epic source.
  await page.getByRole('button', { name: 'Tạo nhanh cấu trúc', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Thêm epic', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Mã epic (NDS-E-00946)', { exact: true }).fill('TC-QUICK');
  await dialog.getByLabel('Tên', { exact: true }).fill('TC quick Epic');
  await dialog.getByRole('button', { name: 'Tạo', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const quick = (await metadata()).epics.find((row: { code: string }) => row.code === 'TC-QUICK');
  expect(quick.key).toMatch(/^STRUI-/);
  await page.goto('/projects/STRUI/backlog');
  await page.getByRole('combobox', { name: 'Lọc Epic', exact: true }).press('ArrowDown');
  await expect(page.locator('.ant-select-dropdown:visible').getByText('TC-QUICK · TC quick Epic', { exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Lọc Epic', exact: true }).press('Escape');
  const backlog = page.getByTestId('backlog-scroll');
  await backlog.getByText('Create', { exact: true }).last().click();
  const quickTitle = backlog.getByPlaceholder(/Bạn cần làm gì/);
  const quickRow = backlog.locator('.issue-row').filter({ has: page.getByPlaceholder(/Bạn cần làm gì/) });
  await choose(quickRow.getByRole('combobox'), 'Epic');
  await quickTitle.fill('Backlog quick Epic');
  const quickCreated = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().endsWith('/projects/STRUI/issues'));
  await quickTitle.press('Enter');
  expect((await quickCreated).ok()).toBeTruthy();
  await expect.poll(async () => (await metadata()).epics.some((row: { name: string }) => row.name === 'Backlog quick Epic')).toBeTruthy();
  await page.goto('/projects/STRUI/test-cases');
  await page.getByPlaceholder('Tìm mã/tên function').fill('Backlog quick Epic');
  await expect(page.getByText(/Backlog quick Epic/).first()).toBeVisible();
});
